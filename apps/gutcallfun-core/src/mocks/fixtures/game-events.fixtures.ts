/**
 * Deterministic `game_event` rows (D-04) — a contiguous run for game_id 3
 * (the "live" fixture) with strictly increasing `seq` starting at 1, so both
 * the `after_seq` cursor behaviour and the end-of-log case are exercisable.
 * No non-deterministic random-number, wall-clock-read, or random-id
 * generation anywhere in this file — timestamps below are computed from a
 * fixed literal base instant.
 */
function eventId(n: number): string {
  return `00000000-0000-4000-8000-${String(n).padStart(12, '0')}`;
}

function feedTs(offsetSeconds: number): string {
  const base = Date.parse('2026-07-18T15:00:00.000Z');
  return new Date(base + offsetSeconds * 1000).toISOString();
}

